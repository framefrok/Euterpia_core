# core/codec_api.nim
#
# Общий контракт форматов аудиофайлов (issue #356, продолжение #10).
#
# До этого `AudioFileInfo` и `AudioFileFormat` жили внутри `wav_codec` — файла
# ОДНОГО формата. Из-за этого контракт и реализация были перепутаны: любой
# вызывающий (фасад `audio_file_io`, `offline_render`, CLI, тесты) тянул
# `wav_codec` ради типа, а с приходом FLAC (#10) `flac_codec` пришлось бы
# импортировать соседний кодек — «реализация знает о реализации».
#
# Здесь только данные контракта: ни потока, ни RIFF, ни аллокаций. Реализации
# (`wav_codec`, будущий `flac_codec`, ...) зависят от этого модуля, а не друг
# от друга; фасад зависит и от контракта, и от реализаций.
#
# `wav_codec` реэкспортирует этот модуль, поэтому старый код, импортирующий
# только `wav_codec`, продолжает компилироваться без изменений.

type
  AudioFileFormat* = enum
    ## Форматы аудиофайлов, о которых знает ядро. Реализованы (или будут)
    ## отдельными модулями-адаптерами: `afWav` — `wav_codec`, остальные —
    ## заглушки до появления соответствующих кодеков.
    afWav
    afFlac
    afOgg
    afMp3
    afAiff

  AudioFileInfo* = object
    ## Метаданные аудиофайла. Общий тип для чтения и записи: кодек заполняет
    ## его при открытии, фасад и вызывающие читают/задают поля.
    sampleRate*: int32
    channels*: int16
    bitsPerSample*: int16
    numFrames*: int64
    isFloat*: bool
    format*: AudioFileFormat
    duration*: float64
