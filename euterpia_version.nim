# euterpia_version.nim
#
# Единый источник версии EUTERPIA.
#
# Версия объявлена РОВНО ЗДЕСЬ и используется двумя потребителями:
#   * `euterpia.nimble` — nimble-скрипт импортирует этот модуль и берёт
#     `EuterpiaVersion` в поле `version` пакета;
#   * CLI (`cli/context.nim`) — печатает её в `euterpia --version`.
#
# Поэтому `euterpia --version` не может разойтись с версией пакета
# (критерий приёмки issue #88), а релиз (#113) правит одно место.
#
# ВАЖНО: модуль обязан оставаться чистым (без `import` и без I/O) —
# его импортирует nimscript-файл пакета, где доступен не весь язык.

const EuterpiaVersion* = "0.3.2"
